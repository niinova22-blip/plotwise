"""
Renders every voiced line to audio for Ozan.

  npx jest --testRegex "export-lines\\.jest\\.ts$"     # writes out/lines.json
  tools/voice/.venv/Scripts/python tools/voice/render.py --lang all

Pipeline per line: Chatterbox Multilingual (MIT) with mood-specific settings,
cloned from one licensed synthetic reference voice (Kokoro bm_george, Apache-2.0)
so Ozan sounds the same in both languages -> trim silence -> loudness-normalise
-> AAC .m4a in assets/voice/<lang>/ -> 20 ms envelope -> src/mentor/voice/manifest.ts.
Lines whose text and settings are unchanged are skipped (out/cache.json).
"""

import argparse
import hashlib
import html
import json
import subprocess
import sys
from pathlib import Path

import numpy as np
import soundfile as sf

from envelope import envelope

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUT = HERE / "out"
ASSETS = ROOT / "assets" / "voice"
MANIFEST = ROOT / "src" / "mentor" / "voice" / "manifest.ts"
REF = HERE / "ref.wav"

# (exaggeration, cfg_weight) per mood.
MOOD = {
    "warm": (0.5, 0.5),
    "empathy": (0.35, 0.3),
    "happy": (0.7, 0.4),
    "think": (0.4, 0.3),
    "curious": (0.6, 0.45),
}
# The reference is English; a near-zero cfg keeps its accent out of Turkish.
TR_CFG = 0.05

REF_TEXT = (
    "Come, sit by the lantern for a while. Every good journey begins with a simple question, "
    "and there is no hurry at all. We will look at the road together, step by step, "
    "and see which paths are worth walking."
)


def file_id(line_id: str) -> str:
    return line_id.replace(".", "_")


def make_reference() -> None:
    from kokoro import KPipeline

    pipe = KPipeline(lang_code="b")
    chunks = [audio for _, _, audio in pipe(REF_TEXT, voice="bm_george", speed=0.9)]
    sf.write(REF, np.concatenate([np.asarray(c) for c in chunks]), 24000)
    print(f"reference written: {REF}")


def ffmpeg(*args: str) -> None:
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", *args], check=True)


def settings_for(lang: str, mood: str) -> tuple[float, float]:
    ex, cfg = MOOD.get(mood, MOOD["warm"])
    return (ex, TR_CFG if lang == "tr" else cfg)


def render(lang: str, lines: list[dict], only: set[str], cache: dict) -> dict:
    from chatterbox.mtl_tts import ChatterboxMultilingualTTS

    model = ChatterboxMultilingualTTS.from_pretrained(device="cuda")
    out_dir = ASSETS / lang
    out_dir.mkdir(parents=True, exist_ok=True)
    tmp = OUT / "tmp"
    tmp.mkdir(parents=True, exist_ok=True)
    entries = {}
    for n, line in enumerate(lines):
        ex, cfg = settings_for(lang, line["mood"])
        key = hashlib.sha1(f"{line['text']}|{ex}|{cfg}".encode()).hexdigest()
        fid = file_id(line["id"])
        m4a = out_dir / f"{fid}.m4a"
        cached = cache.get(lang, {}).get(line["id"])
        if cached and cached["key"] == key and m4a.exists() and line["id"] not in only:
            entries[line["id"]] = cached
            continue
        wav = model.generate(line["text"], language_id=lang, audio_prompt_path=str(REF), exaggeration=ex, cfg_weight=cfg)
        raw = tmp / f"{fid}.raw.wav"
        trimmed = tmp / f"{fid}.wav"
        sf.write(raw, wav.squeeze(0).cpu().numpy(), model.sr)
        ffmpeg(
            "-i", str(raw),
            "-af", "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.05,"
                   "areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.12,areverse,"
                   "loudnorm=I=-18:TP=-1.5:LRA=11",
            "-ar", "24000", "-ac", "1", str(trimmed),
        )
        samples, sr = sf.read(trimmed)
        ffmpeg("-i", str(trimmed), "-c:a", "aac", "-b:a", "64k", str(m4a))
        entries[line["id"]] = {
            "key": key,
            "file": f"{lang}/{fid}.m4a",
            "durationMs": int(round(len(samples) / sr * 1000)),
            "env": envelope(samples, sr),
            "text": line["text"],
            "mood": line["mood"],
        }
        cache.setdefault(lang, {})[line["id"]] = entries[line["id"]]
        if n % 10 == 0:
            (OUT / "cache.json").write_text(json.dumps(cache), encoding="utf-8")
            print(f"[{lang}] {n + 1}/{len(lines)} {line['id']}", flush=True)
    return entries


def write_manifest(all_entries: dict) -> None:
    rows = ["/* Generated by tools/voice/render.py. Do not edit. */", "", "export type Clip = { audio: number; durationMs: number; env: number[] };", ""]
    rows.append("/** env values are 0..100 per 20 ms frame. */")
    rows.append("export const MANIFEST: Record<'en' | 'tr', Record<string, Clip>> = {")
    for lang in ("en", "tr"):
        rows.append(f"  {lang}: {{")
        for line_id, e in sorted(all_entries.get(lang, {}).items()):
            rows.append(f"    '{line_id}': {{ audio: require('../../../assets/voice/{e['file']}'), durationMs: {e['durationMs']}, env: [{','.join(map(str, e['env']))}] }},")
        rows.append("  },")
    rows.append("};")
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text("\n".join(rows) + "\n", encoding="utf-8")


def write_review(all_entries: dict) -> None:
    rows = []
    for lang in ("tr", "en"):
        for line_id, e in sorted(all_entries.get(lang, {}).items()):
            src = (ASSETS / e["file"]).as_uri()
            rows.append(
                f"<tr><td>{lang}</td><td><code>{html.escape(line_id)}</code></td><td>{html.escape(e['mood'])}</td>"
                f"<td>{html.escape(e['text'])}</td><td><audio controls preload='none' src='{src}'></audio></td></tr>"
            )
    page = (
        "<!doctype html><meta charset='utf-8'><title>Ozan voice review</title>"
        "<style>body{font:14px system-ui;margin:20px}td{border-bottom:1px solid #ddd;padding:6px;vertical-align:middle}</style>"
        "<h1>Ozan voice review</h1><p>Write down the id of any line that sounds wrong.</p>"
        f"<table>{''.join(rows)}</table>"
    )
    (OUT / "review.html").write_text(page, encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lang", default="all", choices=["en", "tr", "all"])
    ap.add_argument("--only", default="", help="comma-separated ids to force re-render")
    ap.add_argument("--limit", type=int, default=0, help="render only the first N lines (smoke test)")
    args = ap.parse_args()

    lines = json.loads((OUT / "lines.json").read_text(encoding="utf-8"))
    cache_path = OUT / "cache.json"
    cache = json.loads(cache_path.read_text(encoding="utf-8")) if cache_path.exists() else {}
    if not REF.exists():
        make_reference()
    only = {s for s in args.only.split(",") if s}
    langs = ["en", "tr"] if args.lang == "all" else [args.lang]
    all_entries = {lang: dict(cache.get(lang, {})) for lang in ("en", "tr")}
    for lang in langs:
        todo = lines[lang][: args.limit] if args.limit else lines[lang]
        all_entries[lang].update(render(lang, todo, only, cache))
        cache_path.write_text(json.dumps(cache), encoding="utf-8")
    # Drop entries for lines that no longer exist in the script.
    for lang in ("en", "tr"):
        valid = {l["id"] for l in lines[lang]}
        all_entries[lang] = {k: v for k, v in all_entries[lang].items() if k in valid}
    write_manifest(all_entries)
    write_review(all_entries)
    print("manifest and review written")


if __name__ == "__main__":
    sys.exit(main())
